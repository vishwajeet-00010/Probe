"use client";
import { useState } from "react";
import { useApp } from "../app-provider";
import { Plus, Download, Share2, FileCheck2 } from "lucide-react";
import type { Report } from "@/types/domain";
import { Badge, Empty, Field, Modal } from "../ui";
import { Heading } from "./heading";
import {
  createShare,
  downloadReportPdf,
  exportEntriesCsv,
  generateReport,
  revokeShare,
} from "@/lib/data";
export const reportSections = [
  "Temperature records",
  "Checklist completion",
  "Deliveries",
  "Corrective actions",
  "Cleaning records",
  "Sign-offs",
];
export function Reports() {
  const { state, site, actor, act, busy } = useApp();
  const [builder, setBuilder] = useState(false),
    [share, setShare] = useState<Report | null>(null),
    [url, setUrl] = useState(""),
    [error, setError] = useState("");
  return (
    <>
      <Heading
        title="Reports"
        description="Your daily records, ready for a closer look."
      >
        <button
          className="btn"
          disabled={busy}
          onClick={() =>
            act(() => exportEntriesCsv(actor), "Export ready.").catch(() => {})
          }
        >
          <Download size={15} />
          Full CSV export
        </button>
        <button className="btn primary" onClick={() => setBuilder(true)}>
          <Plus size={16} />
          Generate inspection pack
        </button>
      </Heading>
      <div
        className="card card-pad row between"
        style={{ background: "var(--pale)", marginBottom: 24 }}
      >
        <div>
          <span className="eyebrow">INSPECTION READY</span>
          <h2 style={{ margin: "8px 0" }}>90 days. One clear picture.</h2>
          <p className="muted">
            Choose your dates and sections. Generate a PDF snapshot of the
            evidence.
          </p>
        </div>
        <FileCheck2 size={42} strokeWidth={1} />
      </div>
      <section className="card">
        <div className="card-head">
          <h2>Report history</h2>
          <small>{state.reports.length} reports</small>
        </div>
        <div className="table-wrap">
          <table>
            <thead>
              <tr>
                {["Report", "Period", "Generated by", "Status", "Actions"].map(
                  (h) => (
                    <th key={h}>{h}</th>
                  ),
                )}
              </tr>
            </thead>
            <tbody>
              {state.reports.map((r) => (
                <tr key={r.id}>
                  <td>
                    <strong>{r.name}</strong>
                    <p className="muted" style={{ fontSize: 10 }}>
                      {r.id}
                    </p>
                    <small>
                      {new Date(r.generatedAt).toLocaleString("en-GB", {
                        timeZone: "UTC",
                      })}
                    </small>
                  </td>
                  <td>
                    {r.start} – {r.end}
                  </td>
                  <td>{r.generatedBy}</td>
                  <td>
                    <Badge status={r.status} />
                  </td>
                  <td>
                    <div className="row">
                      <button
                        className="btn"
                        disabled={busy}
                        onClick={() =>
                          act(() => downloadReportPdf(actor, r.id), "").catch(
                            () => {},
                          )
                        }
                      >
                        <Download size={13} />
                        PDF
                      </button>
                      <button
                        className="btn"
                        onClick={() => {
                          setShare(r);
                          setUrl("");
                          setError("");
                        }}
                      >
                        <Share2 size={13} />
                        Share
                      </button>
                    </div>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
        {!state.reports.length && (
          <Empty text="No reports yet. Generate your first inspection pack." />
        )}
      </section>
      {state.shareLinks.length > 0 && (
        <section className="card" style={{ marginTop: 24 }}>
          <div className="card-head">
            <h2>Inspector links</h2>
          </div>
          {state.shareLinks.map((l) => (
            <div className="card-pad row between" key={l.id}>
              <div>
                <p>
                  Report {l.reportId.slice(0, 8)} · {l.accesses} accesses
                </p>
                <small>
                  Expires{" "}
                  {new Date(l.expiresAt).toLocaleString("en-GB", {
                    timeZone: "UTC",
                  })}
                </small>
              </div>
              {l.revoked ? (
                <Badge status="Revoked" />
              ) : (
                <button
                  className="btn danger"
                  onClick={() =>
                    act(() => revokeShare(actor, l.id), "Link revoked.").catch(
                      () => {},
                    )
                  }
                >
                  Revoke link
                </button>
              )}
            </div>
          ))}
        </section>
      )}
      {builder && (
        <ReportBuilder site={site} onClose={() => setBuilder(false)} />
      )}{" "}
      {share && (
        <Modal title="Share with an inspector" onClose={() => setShare(null)}>
          <form
            className="stack"
            onSubmit={async (e) => {
              e.preventDefault();
              const f = new FormData(e.currentTarget);
              try {
                const days = Number(f.get("days")) as 1 | 7 | 30;
                setUrl(
                  await act(
                    () => createShare(actor, state, share.id, days),
                    "Link created.",
                  ),
                );
              } catch (e) {
                setError(e instanceof Error ? e.message : "Unable to share.");
              }
            }}
          >
            <p className="muted">
              Anyone with this link can view this report snapshot. It cannot
              expose other business records.
            </p>
            <Field label="Link expires after">
              <select name="days">
                <option value="1">24 hours</option>
                <option value="7">7 days</option>
                <option value="30">30 days</option>
              </select>
            </Field>
            {error && <p className="error">{error}</p>}
            <button className="btn primary" disabled={busy}>
              Create read-only link
            </button>
            {url && (
              <>
                <Field label="Inspector URL — copy and store this now">
                  <input
                    readOnly
                    value={url}
                    onFocus={(e) => e.target.select()}
                  />
                </Field>
                <a className="btn" href={url} target="_blank" rel="noreferrer">
                  Open inspector view
                </a>
              </>
            )}
          </form>
        </Modal>
      )}
    </>
  );
}
function ReportBuilder({
  site,
  onClose,
}: {
  site: string;
  onClose: () => void;
}) {
  const { state, actor, act, busy } = useApp(),
    [error, setError] = useState(""),
    [start, setStart] = useState(
      new Date(new Date().getTime() - 90 * 86400000).toISOString().slice(0, 10),
    ),
    [end, setEnd] = useState(new Date().toISOString().slice(0, 10)),
    [sections, setSections] = useState(reportSections);
  return (
    <Modal title="Generate inspection pack" onClose={onClose}>
      <form
        className="stack"
        onSubmit={async (e) => {
          e.preventDefault();
          try {
            await act(
              () =>
                generateReport(actor, state, {
                  name: "Inspection pack",
                  start,
                  end,
                  siteIds: [site],
                  sections,
                }),
              "Report generated.",
            );
            onClose();
          } catch (e) {
            setError(
              e instanceof Error ? e.message : "Unable to generate report.",
            );
          }
        }}
      >
        <div className="form-grid">
          <Field label="Start date">
            <input
              type="date"
              value={start}
              onChange={(e) => setStart(e.target.value)}
              required
            />
          </Field>
          <Field label="End date">
            <input
              type="date"
              value={end}
              onChange={(e) => setEnd(e.target.value)}
              required
            />
          </Field>
        </div>
        <h3>Included sections</h3>
        {reportSections.map((s) => (
          <label className="check-label" key={s}>
            <input
              type="checkbox"
              checked={sections.includes(s)}
              onChange={(e) =>
                setSections(
                  e.target.checked
                    ? [...sections, s]
                    : sections.filter((x) => x !== s),
                )
              }
            />
            {s}
          </label>
        ))}
        <div className="report-preview">
          <span className="eyebrow">PROBE · INSPECTION PACK</span>
          <h2 style={{ fontSize: 24, margin: "20px 0" }}>
            {state.organization.name}
          </h2>
          <p>{state.organization.address}</p>
          <p className="muted">
            {start} — {end}
          </p>
          <hr
            style={{ border: 0, borderTop: "1px solid #ddd", margin: "25px 0" }}
          />
          <h3>Contents preview</h3>
          {sections.map((s, i) => (
            <p key={s} style={{ marginTop: 10 }}>
              {i + 1}. {s}
            </p>
          ))}
          <small>Final PDF snapshots selected records when generated.</small>
        </div>
        {error && <p className="error">{error}</p>}
        <button className="btn primary" disabled={busy || !sections.length}>
          {busy ? "Generating…" : "Generate PDF report"}
        </button>
      </form>
    </Modal>
  );
}
